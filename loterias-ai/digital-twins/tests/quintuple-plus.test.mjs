assert.equal(q.classifyTicket({ticket:[1,2,3,9,5,6],outcome:[1,2,3,4,5,6]}),3);
assert.equal(q.classifyTicket({ticket:[1,2,3,9,5,7],outcome:[1,2,3,4,5,6]}),4);
